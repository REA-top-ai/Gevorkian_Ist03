# -------------------------------------------------------------
# Ключ словаря -> имя столбца, значение -> список значений столбца.
# Все списки должны быть одинаковой длины.
# Столбцы располагаются в алфавитном порядке (словарь не хранит порядок).

df1 = pd.DataFrame({
    'name': ['John Smith', 'Jane Doe', 'Joe Schmo'],
    'address': ['123 Main St.', '456 Maple Ave.', '789 Broadway'],
    'age': [34, 28, 51]
})
print("df1 (создание через словарь):")
print(df1, "\n")


# -------------------------------------------------------------
# 3. Создание DataFrame II (через список списков)
# -------------------------------------------------------------
# Каждый вложенный список — это одна строка данных.
# Аргумент columns задаёт имена и порядок столбцов (порядок сохраняется).

df2 = pd.DataFrame([
    ['John Smith', '123 Main St.', 34],
    ['Jane Doe', '456 Maple Ave.', 28],
    ['Joe Schmo', '789 Broadway', 51]
    ],
    columns=['name', 'address', 'age'])
print("df2 (создание через список списков):")
print(df2, "\n")


